/**
 * Generate a shuffled list of words from the word bank
 * @param {number} count - Number of words to generate
 * @param {string} language - 'english' or 'indonesian'
 * @returns {string[]}
 */
export function generateWords(count = 50, language = 'english') {
  const bank = wordBanks[language] || englishWords
  const words = []
  for (let i = 0; i < count; i++) {
    const randomIndex = Math.floor(Math.random() * bank.length)
    words.push(bank[randomIndex])
  }
  return words
}
